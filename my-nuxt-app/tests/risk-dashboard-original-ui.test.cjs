function load(name, imports = {}) {
  const source = fs.readFileSync(path.join(root, 'app/utils', name), 'utf8')
  const exports = {}
  const result = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }, reportDiagnostics: true })
  assert.equal(result.diagnostics.length, 0)
  vm.runInNewContext(result.outputText, { exports, require: name => { assert(Object.hasOwn(imports, name), name); return imports[name] }, setTimeout: () => {} })
  return exports
}
