import MarkdownIt, { type Env } from 'markdown-it'

const citationIdPattern = /^E[1-9]\d*$/
const citationPattern = /\[(E[1-9]\d*)\]/g

interface AnswerEnvironment extends Env {
  citationIds: Set<string>
}

const markdown = new MarkdownIt({
  html: false,
  linkify: false,
  typographer: false,
})

// CommonMark does not close emphasis after punctuation when Han text follows.
// Accept short Han labels or bounded plain-text Chinese sentences in this case.
// The allowlist excludes newlines and inline syntax, including escapes and stars.
// An inline rule keeps escapes/code intact; link labels retain standard parsing.
markdown.inline.ruler.before('emphasis', 'rag_han_strong', (state, silent) => {
  if (silent || state.linkLevel > 0 || state.src[state.pos] !== '*' || state.src[state.pos - 1] === '*') return false
  const match = /^\*\*((?:[\p{Script=Han}]{1,40}[：:]|\p{Script=Han}[\p{Script=Han}A-Za-z0-9，、；：:。！？（）“”‘’《》·— \t-]{0,238}[。！？]))\*\*(?=\p{Script=Han})/u.exec(
    state.src.slice(state.pos, Math.min(state.posMax, state.pos + 486)),
  )
  if (!match) return false
  state.push('strong_open', 'strong', 1).markup = '**'
  state.push('text', '', 0).content = match[1]!
  state.push('strong_close', 'strong', -1).markup = '**'
  state.pos += match[0].length
  return true
})

// Answers can link to external sources, but cannot navigate to active/local schemes.
markdown.validateLink = (value: string): boolean => {
  if (!/^https?:\/\//i.test(value) || /[\u0000-\u0020\u007f]/.test(value)) return false
  try {
    const url = new URL(value)
    return url.protocol === 'https:' || url.protocol === 'http:'
  } catch {
    return false
  }
}

markdown.renderer.rules.link_open = (tokens, index, options, _env, renderer) => {
  const token = tokens[index]!
  token.attrSet('target', '_blank')
  token.attrSet('rel', 'noopener noreferrer')
  return renderer.renderToken(tokens, index, options)
}

// Never load model-supplied images, including tracking pixels and data images.
markdown.renderer.rules.image = (tokens, index, options, env, renderer) => {
  const token = tokens[index]!
  const alt = renderer.renderInlineAsText(token.children ?? [], options, env)
  return `<span class="rag-image-alt">${markdown.utils.escapeHtml(alt || '图片')}</span>`
}

// Work on parsed text only: code, image alt text and link labels are excluded.
markdown.core.ruler.after('text_join', 'rag_citations', (state) => {
  for (const block of state.tokens) {
    if (block.type !== 'inline' || !block.children) continue
    let linkDepth = 0
    for (const token of block.children) {
      if (token.type === 'link_open') linkDepth += 1
      else if (token.type === 'link_close') linkDepth = Math.max(0, linkDepth - 1)
      else if (token.type === 'text' && linkDepth === 0) token.type = 'rag_answer_text'
    }
  }
})

markdown.renderer.rules.rag_answer_text = (tokens, index, _options, env) => {
  const escaped = markdown.utils.escapeHtml(tokens[index]!.content)
  const allowedIds = (env as AnswerEnvironment).citationIds
  return escaped.replace(citationPattern, (original, id: string) => allowedIds.has(id)
    ? `<button type="button" class="rag-citation" data-citation-id="${id}" aria-label="查看引用 ${id}">${original}</button>`
    : original)
}

/** The only HTML accepted by RagAnswer is generated by this configured parser. */
export function renderRagMarkdown(content: string, citationIds: readonly string[] = []): string {
  const allowedIds = new Set(citationIds.filter(id => citationIdPattern.test(id)))
  return markdown.render(content, { citationIds: allowedIds } satisfies AnswerEnvironment)
}
