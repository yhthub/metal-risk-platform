# 三元组提取与问题分类
# ============================================================
def classify_question(question: str) -> str:
    """
    自动分类问题类型

    Args:
        question: 用户问题

    Returns:
        问题类型
    """
    question_lower = question.lower()

    # 计算每个类型的匹配分数
    scores = {}
    for q_type, info in QUESTION_PATTERNS.items():
        score = sum(1 for kw in info["keywords"] if kw in question_lower)
        scores[q_type] = score

    # 返回得分最高的类型
    if max(scores.values()) > 0:
        return max(scores, key=scores.get)

    return "综合咨询"


def extract_triples(question: str) -> dict:
    """
    从问题中提取关键三元组

    Args:
        question: 用户问题

    Returns:
        提取的三元组信息
    """
    # 重金属关键词
    metals = {
        "铅": "Pb", "镉": "Cd", "汞": "Hg", "砷": "As", "铬": "Cr",
        "镍": "Ni", "锰": "Mn", "铊": "Tl", "锂": "Li", "钴": "Co",
        "Pb": "铅", "Cd": "镉", "Hg": "汞", "As": "砷", "Cr": "铬"
    }

    # 靶器官关键词
    organs = {
        "肾": "肾脏", "肝": "肝脏", "脑": "脑/神经系统", "神经": "神经系统",
        "肺": "肺脏", "骨": "骨骼", "血": "血液系统", "心": "心血管系统",
        "皮肤": "皮肤", "眼": "眼睛", "生殖": "生殖系统"
    }

    # 健康效应关键词
    effects = {
        "中毒": "急性/慢性中毒", "癌": "致癌效应", "损伤": "器官损伤",
        "病变": "病理改变", "障碍": "功能障碍", "衰竭": "器官衰竭",
        "纤维化": "组织纤维化", "硬化": "组织硬化", "贫血": "血液系统异常"
    }

    # 提取暴露因素
    exposure = []
    for cn, en in metals.items():
        if cn in question:
            exposure.append(f"{cn}({en})")

    # 提取靶器官
    target = []
    for keyword, organ in organs.items():
        if keyword in question:
            target.append(organ)

    # 提取健康效应
    effect = []
    for keyword, desc in effects.items():
        if keyword in question:
            effect.append(desc)

    return {
        "exposure": list(set(exposure)) if exposure else ["未明确"],
        "target": list(set(target)) if target else ["未明确"],
        "effect": list(set(effect)) if effect else ["未明确"],
        "type": classify_question(question)
    }


# ============================================================
# 构建专业 Prompt
# ============================================================
def build_professional_prompt(question: str, question_type: str = None) -> str:
    """
    构建专业的公共卫生领域 Prompt

    Args:
        question: 用户原始问题
        question_type: 问题类型（可选，自动识别）

    Returns:
        组合后的专业 Prompt
    """
    # 自动识别问题类型
    if not question_type:
        question_type = classify_question(question)

    # 获取问题类型的焦点
    type_info = QUESTION_PATTERNS.get(question_type, {})
    focus = type_info.get("focus", "综合分析")
    evidence_source = type_info.get("evidence_source", "权威医学文献")

    # 提取三元组
    triples = extract_triples(question)

    # 构建专业 Prompt
    prompt = f"""【问题分析】
用户问题：{question}
问题类型：{question_type}
分析重点：{focus}
证据来源：{evidence_source}

【提取的关键信息】
- 暴露因素：{', '.join(triples['exposure'])}
- 靶器官/系统：{', '.join(triples['target'])}
- 健康效应：{', '.join(triples['effect'])}

{ANSWER_PRINCIPLES}

{ANSWER_TEMPLATE}

【特别提示】
1. 请严格按照上述回答结构组织内容
2. 所有医学结论必须有依据，引用权威来源
3. 风险评估请给出明确的分级
4. 干预建议请区分紧急措施和长期措施
5. 若证据不足请明确说明

请开始回答："""

    return prompt


